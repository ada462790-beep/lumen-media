//go:build unix

package scheibe

import "syscall"

// FreierPlatz meldet die freien Bytes im Ordner (0, wenn unbekannt).
func FreierPlatz(dir string) uint64 {
	var st syscall.Statfs_t
	if err := syscall.Statfs(dir, &st); err != nil {
		return 0
	}
	return st.Bavail * uint64(st.Bsize)
}
